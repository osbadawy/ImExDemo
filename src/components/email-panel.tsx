"use client";

import { motion } from "framer-motion";
import { Check, CheckCheck, Copy, Eye, Send, Sparkles } from "lucide-react";
import { useEffect, useState } from "react";
import { Modal } from "./modal";
import { useToast } from "./toast";
import { AgentAvatar, Button } from "./ui";
import type { AgentId } from "@/data/agents";
import { cn } from "@/lib/format";

export interface DraftEmail {
  to: string;
  cc?: string;
  subject: string;
  body: string;
}

/** Modal showing an AI-drafted email with a streaming reveal, copy, review and simulated approval. */
export function EmailPanel({
  open,
  onClose,
  email,
  agent = "document",
  agentName = "Document Intelligence",
  color = "#4f5bd5",
}: {
  open: boolean;
  onClose: () => void;
  email: DraftEmail;
  agent?: AgentId;
  agentName?: string;
  color?: string;
}) {
  const toast = useToast();
  const [chars, setChars] = useState(0);
  const [reviewed, setReviewed] = useState(false);
  const [approved, setApproved] = useState(false);
  const full = email.body;
  const done = chars >= full.length;

  useEffect(() => {
    if (!open) return;
    setChars(0);
    setReviewed(false);
    setApproved(false);
    const iv = setInterval(() => setChars((c) => (c >= full.length ? c : c + 6)), 16);
    return () => clearInterval(iv);
  }, [open, full]);

  const copy = async () => {
    const text = `To: ${email.to}\nSubject: ${email.subject}\n\n${email.body}`;
    try {
      await navigator.clipboard.writeText(text);
    } catch {
      const ta = document.createElement("textarea");
      ta.value = text;
      document.body.appendChild(ta);
      ta.select();
      document.execCommand("copy");
      ta.remove();
    }
    toast({ title: "Email copied to clipboard" });
  };

  return (
    <Modal open={open} onClose={onClose}>
      <div className="flex items-center gap-3 border-b border-line px-6 py-4">
        <AgentAvatar agent={agent} color={color} state={done ? "complete" : "working"} size={36} />
        <div>
          <div className="text-[15px] font-semibold">{done ? "Draft ready for review" : "Drafting email…"}</div>
          <div className="text-xs text-ink-3">Generated by {agentName} agent · demo, nothing is sent</div>
        </div>
      </div>
      <div className="scrollbar-thin max-h-[60vh] overflow-y-auto px-6 py-5">
        <div className="mb-4 flex flex-col gap-2 rounded-xl border border-line bg-canvas/60 p-3.5 text-[13px]">
          <div className="flex gap-3"><span className="w-14 text-ink-3">To</span><span className="text-ink">{email.to}</span></div>
          {email.cc && <div className="flex gap-3"><span className="w-14 text-ink-3">Cc</span><span className="text-ink">{email.cc}</span></div>}
          <div className="flex gap-3"><span className="w-14 text-ink-3">Subject</span><span className="font-medium text-ink">{email.subject}</span></div>
        </div>
        <div className="whitespace-pre-wrap text-[14px] leading-[1.7] text-ink-2">
          {full.slice(0, chars)}
          {!done && <motion.span className="ml-0.5 inline-block h-4 w-[2px] translate-y-0.5 bg-brand" animate={{ opacity: [1, 0] }} transition={{ duration: 0.6, repeat: Infinity }} />}
        </div>
      </div>
      <div className="flex flex-col gap-3 border-t border-line bg-canvas/50 px-6 py-4 sm:flex-row sm:items-center sm:justify-between">
        <div className="flex items-center gap-2 text-xs text-ink-3">
          {approved ? (
            <span className="flex items-center gap-1.5 font-medium text-mint">
              <CheckCheck className="size-4" /> Approved · saved to outbox (simulated, not sent)
            </span>
          ) : reviewed ? (
            <span className="flex items-center gap-1.5 font-medium text-brand">
              <Eye className="size-4" /> Marked as reviewed
            </span>
          ) : (
            <span className="flex items-center gap-1.5">
              <Sparkles className="size-3.5" /> Human review required before sending
            </span>
          )}
        </div>
        <div className="flex flex-wrap gap-2">
          <Button size="sm" icon={Copy} onClick={copy} disabled={!done}>Copy</Button>
          <Button
            size="sm"
            icon={reviewed ? Check : Eye}
            disabled={!done || reviewed}
            onClick={() => {
              setReviewed(true);
              toast({ title: "Marked as reviewed", tone: "info" });
            }}
          >
            {reviewed ? "Reviewed" : "Mark reviewed"}
          </Button>
          <Button
            size="sm"
            variant="primary"
            icon={approved ? CheckCheck : Send}
            disabled={!done || approved}
            className={cn(approved && "!bg-mint")}
            onClick={() => {
              setReviewed(true);
              setApproved(true);
              toast({ title: "Approval simulated", body: "In a live deployment this would be sent from your mailbox." });
            }}
          >
            {approved ? "Approved" : "Approve"}
          </Button>
        </div>
      </div>
    </Modal>
  );
}
